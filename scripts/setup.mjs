import { randomBytes } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { readLocalEnvironment } from './environment.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(root, '.env');
const args = process.argv.slice(2);
if (args.some((arg) => arg !== '--show-credentials')) {
  console.error('Usage: node scripts/setup.mjs [--show-credentials]');
  process.exit(1);
}

const values = {
  POSTGRES_PASSWORD: randomBytes(24).toString('base64url'),
  JWT_KEY: randomBytes(48).toString('base64url'),
  DEMO_PASSWORD: `Tf!${randomBytes(15).toString('base64url')}9aA`,
  DEMO_ENABLED: 'true',
  TASKFLOW_PORT: '8080',
  HOLIDAY_API_MODE: 'Stub',
  HOLIDAY_API_STUB_SCENARIO: 'Success',
};

try {
  await writeFile(envPath, [
    '# Local secrets generated by scripts/setup.mjs. Never commit this file.',
    ...Object.entries(values).map(([key, value]) => `${key}=${value}`),
    '',
  ].join('\n'), { flag: 'wx', mode: 0o600 });
  console.log('Created .env with random local secrets.');
} catch (error) {
  if (error.code !== 'EEXIST') throw error;
  console.log('Using existing .env; its values were preserved.');
}

const envValues = await readLocalEnvironment();
const missing = ['POSTGRES_PASSWORD', 'JWT_KEY', 'DEMO_PASSWORD'].filter((key) => !envValues[key]);
if (missing.length) {
  console.error(`Set the following values in .env: ${missing.join(', ')}.`);
  process.exit(1);
}

console.log('Start: docker compose up --build --detach --wait');
console.log('Open: http://localhost:' + (envValues.TASKFLOW_PORT || '8080'));
if (args.includes('--show-credentials')) {
  console.log('Demo accounts: owner@taskflow.local, member@taskflow.local, outsider@taskflow.local, admin@taskflow.local');
  console.log(`Demo password: ${envValues.DEMO_PASSWORD}`);
} else {
  console.log('Display demo credentials locally: node scripts/setup.mjs --show-credentials');
}
